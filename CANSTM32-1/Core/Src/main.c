// Interrupt-based routine that triggers when a message is received
void HAL_CAN_RxFifo0MsgPendingCallback(CAN_HandleTypeDef* hcan1){
	if(HAL_CAN_GetRxMessage(hcan1, CAN_RX_FIFO0, &hrx1, &BUTTON_PRESSED) != HAL_OK){
		Error_Handler();
	}
	else{
		if(BUTTON_PRESSED){
			RGB_LED = (RGB_LED + 1 <= 7) ? (RGB_LED + 1) : 0;	 // If user button pressed on other MCU, change RGB LED color
			MSG_LED = (RGB_LED == 0) ? 1 : 0;
			HAL_GPIO_WritePin(GPIOA, GPIO_PIN_0, RGB_LED & 0x01);
			HAL_GPIO_WritePin(GPIOB, GPIO_PIN_0, RGB_LED & 0x02);
			HAL_GPIO_WritePin(GPIOE, GPIO_PIN_0, RGB_LED & 0x04);
			BUTTON_PRESSED = 0;									 // Reset user button SW
		}
	}

	if(HAL_CAN_AddTxMessage(hcan1, &htx1, &MSG_LED, &txMailbox) != HAL_OK){
		Error_Handler();
	}
	else{
		while(HAL_CAN_GetTxMailboxesFreeLevel(hcan1) != 3){} // wait for successful transmission
	}
}
